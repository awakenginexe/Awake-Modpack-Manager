/**
 * REAL Native Core 0.2.1 (manager.v0.2.1, which implies manager.v0.2) through the Manager's own client, against public Modrinth
 * and loader metadata. Opt-in, disposable profiles only:
 *   AWAKE_REAL_HELPER=<0.2 exe> AWAKE_REAL_PROFILE=<new dir> [AWAKE_LEGACY_HELPER=<0.1.1 exe>] npx vitest run tests/realHelper/real020
 * What is live here: helper process, loader metadata, Modrinth API and CDN downloads, on-disk files.
 * What is a fixture: the pack archives are generated by this test (from real Modrinth files).
 */
const exe = process.env.AWAKE_REAL_HELPER;
const profile = process.env.AWAKE_REAL_PROFILE;
const legacyExe = process.env.AWAKE_LEGACY_HELPER;
const FERRITE = 'uXXizFIs';
const UA = { headers: { 'User-Agent': 'awake-modpack-manager-tests' } };
const enc = (s: string) => new TextEncoder().encode(s);
/** Everything logged also lands in <profile>-evidence.json, passing or not. */
const evidence: unknown[] = [];
const log = (...a: unknown[]) => { evidence.push(a); console.log(...a); };
afterAll(() => { if (profile) writeFileSync(`${profile}-evidence.json`, JSON.stringify(evidence, null, 1)); });
const sha = (alg: string, b: Uint8Array | Buffer) => createHash(alg).update(b).digest('hex');

async function modrinthFile(versionId: string) {
  const v = (await (await fetch(`https://api.modrinth.com/v2/version/${versionId}`, UA)).json()) as { project_id: string; version_number: string; files: { url: string; filename: string; size: number; primary: boolean; hashes: { sha1: string; sha512: string } }[] };
  const f = v.files.find((x) => x.primary) ?? v.files[0]!;
  return { projectId: v.project_id, versionId, versionName: v.version_number, ...f };
}
/** Directory of a workspace: the one under workspaceRoot whose instance.cfg names it. */
function workspaceDir(root: string, name: string): string {
  for (const d of readdirSync(root)) {
    const cfg = join(root, d, 'instance.cfg');
    if (existsSync(cfg) && readFileSync(cfg, 'utf8').includes(`name=${name}`)) return join(root, d);
  }
  throw new Error(`workspace ${name} not found under ${root}`);
}
function files(dir: string): string[] {
  const out: string[] = [];
  const walk = (d: string) => { for (const n of readdirSync(d)) { const p = join(d, n); if (statSync(p).isDirectory()) walk(p); else out.push(p); } };
  walk(dir);
  return out;
}

describe.skipIf(!exe || !profile)('REAL Native Core 0.2 (opt-in)', () => {
  // The body is collected even when skipped: only start a transport when opted in.
  const t = exe && profile ? nodeHelperTransport(exe, profile) : null!;
  const client = () => createHelperClient({ transport: t, clientVersion: '0.2.0-real-test', pollMs: 300, startTimeoutMs: 90_000, requestTimeoutMs: 120_000 });
  const session = createSession(client(), { pollMs: 300 });
  let root = '';
  const ids: Record<string, string> = {};

  async function applyDraft(changes: Parameters<typeof addChanges>[1]) {
    session.setDraft(addChanges(session.draft.value!, changes));
    await session.validate();
    expect(session.review.phase, session.review.error?.message).toBe('reviewed');
    const plan = session.review.plan!;
    await session.apply();
    expect(session.review.phase, session.review.error?.message ?? JSON.stringify(session.review.operation)).toBe('done');
    await session.loadInventory();
    return plan;
  }
  async function importArchive(bytes: Uint8Array, format: 'mrpack' | 'curseforge', name: string) {
    const b = session.backend;
    const token = await b.uploadImport!(new Blob([bytes as BlobPart]));
    const ins = await b.inspectImport!(token, format);
    const made = await session.createInstance({ name, minecraftVersion: ins.minecraftVersion, loader: ins.loader.kind, loaderVersion: ins.loader.version || undefined });
    expect(made?.state, JSON.stringify(made?.error)).toBe('completed');
    await session.refreshInstances();
    const plan = await session.prepareImport(made!.result!.instanceId!, token, format, false, name);
    return { ins, plan, id: made!.result!.instanceId! };
  }

  it('negotiates manager.v0.2 and creates Vanilla, Fabric, Forge 1.20.1, NeoForge and Quilt workspaces', async () => {
    await session.connect();
    const hs = session.state.handshake!;
    expect(hs, session.state.connectError?.message).toBeTruthy();
    log('helper', hs.launcherVersion, hs.capabilities.join(','), hs.providers);
    expect(hs.launcherVersion).toBe('0.2.1');
    expect(hs.capabilities).toEqual(expect.arrayContaining(['instances.create', 'plan.apply', 'mods.policies', 'packs.import']));
    expect(hs.providers.find((p) => p.id === 'curseforge')).toMatchObject({ available: false, unavailableReason: 'curseforge-disabled' });
    root = (await session.backend.listInstallations())[0]!.path;

    const want: [LoaderKind, string, string | null][] = [['vanilla', '1.20.1', null], ['fabric', '1.20.1', null], ['forge', '1.20.1', '47.4.28'], ['neoforge', '1.21.1', null], ['quilt', '1.20.1', null]];
    const cat0 = await session.backend.versionCatalog!({});
    expect(cat0.loaders.sort()).toEqual(['fabric', 'forge', 'neoforge', 'quilt', 'vanilla']);
    for (const [loader, mc, prefer] of want) {
      const cat = await session.backend.versionCatalog!({ minecraftVersion: mc, loader: loader === 'vanilla' ? undefined : loader });
      expect(cat.minecraftVersions).toContain(mc);
      const lv = loader === 'vanilla' ? undefined : (prefer && cat.loaderVersions.includes(prefer) ? prefer : cat.loaderVersions[0]);
      if (loader !== 'vanilla') expect(cat.loaderVersions.length, `${loader} ${mc} versions`).toBeGreaterThan(0);
      const name = `Real ${loader} ${mc}`;
      const r = await session.createInstance({ name, minecraftVersion: mc, loader, loaderVersion: lv });
      expect(r?.state, `${loader}: ${JSON.stringify(r?.error)}`).toBe('completed');
      ids[loader] = r!.result!.instanceId!;
      const dir = workspaceDir(root, name);
      const pack = JSON.parse(readFileSync(join(dir, 'mmc-pack.json'), 'utf8')) as { components: { uid: string; version: string }[] };
      log(loader, lv, pack.components.map((c) => `${c.uid}@${c.version}`).join(' '));
      expect(pack.components.find((c) => c.uid === 'net.minecraft')?.version).toBe(mc);
      const uid = { vanilla: null, fabric: 'net.fabricmc.fabric-loader', forge: 'net.minecraftforge', neoforge: 'net.neoforged', quilt: 'org.quiltmc.quilt-loader' }[loader];
      if (uid) expect(pack.components.find((c) => c.uid === uid)?.version).toBe(lv);
    }
    // Incompatible pair: Forge has no build for a very old Minecraft the catalog does not offer for it.
    const forgeCat = await session.backend.versionCatalog!({ loader: 'forge' });
    expect(forgeCat.minecraftVersions).toContain('1.20.1');
  }, 600_000);

  it('installs real Modrinth mods in Fabric and Forge 1.20.1, updates, pins/excludes, toggles and removes', async () => {
    await session.refreshInstances();
    // Fabric 1.20.1: older FerriteCore, then update.
    await session.selectInstance(ids.fabric!);
    const fabricVersions = await session.backend.projectVersions!(ids.fabric!, 'modrinth', FERRITE);
    const oldFabric = fabricVersions.at(-1)!;
    await applyDraft([{ kind: 'install', provider: 'modrinth', projectId: FERRITE, name: 'FerriteCore', versionId: oldFabric.id }]);
    let m = session.inventory.value!.mods.find((x) => x.projectId === FERRITE)!;
    expect(m.installed?.id).toBe(oldFabric.id);
    const file = await modrinthFile(oldFabric.id);
    const onDisk = files(workspaceDir(root, 'Real fabric 1.20.1')).find((p) => p.endsWith(file.filename))!;
    expect(sha('sha512', readFileSync(onDisk))).toBe(file.hashes.sha512);
    expect(m.available?.id, 'a newer stable release is offered').toBe(fabricVersions[0]!.id);
    await applyDraft([{ kind: 'update', modKey: m.key, targetVersionId: m.available!.id }]);
    m = session.inventory.value!.mods.find((x) => x.projectId === FERRITE)!;
    expect(m.installed?.id).toBe(fabricVersions[0]!.id);

    // Forge 1.20.1: exact FerriteCore DG5Fn9Sz, pin + exclude through a reviewed policy, toggle, remove.
    await session.selectInstance(ids.forge!);
    await applyDraft([{ kind: 'install', provider: 'modrinth', projectId: FERRITE, name: 'FerriteCore', versionId: 'DG5Fn9Sz' }]);
    m = session.inventory.value!.mods.find((x) => x.projectId === FERRITE)!;
    expect(m.installed?.id).toBe('DG5Fn9Sz');
    const forgeFile = await modrinthFile('DG5Fn9Sz');
    expect(sha('sha512', readFileSync(files(workspaceDir(root, 'Real forge 1.20.1')).find((p) => p.endsWith(forgeFile.filename))!))).toBe(forgeFile.hashes.sha512);
    session.setPinned([m.key], true);
    session.setExcluded([m.key], true);
    const policyPlan = await applyDraft([]);
    log('policy plan', policyPlan.items.map((i) => `${i.action} ${i.name} ${i.to?.name}`), policyPlan.issues.map((i) => i.message));
    m = session.inventory.value!.mods.find((x) => x.projectId === FERRITE)!;
    expect(m.updateLocked).toBe(true);
    expect(m.updateExcluded).toBe(true);
    expect(readFileSync(join(workspaceDir(root, 'Real forge 1.20.1'), '.awake-integration', 'policies.json'), 'utf8')).toContain('DG5Fn9Sz');
    session.setPinned([m.key], false);
    session.setExcluded([m.key], false);
    await applyDraft([]);
    m = session.inventory.value!.mods.find((x) => x.projectId === FERRITE)!;
    expect([!!m.updateLocked, !!m.updateExcluded]).toEqual([false, false]);
    await applyDraft([{ kind: 'disable', modKey: m.key }]);
    m = session.inventory.value!.mods.find((x) => x.projectId === FERRITE)!;
    expect(m.enabled).toBe(false);
    await applyDraft([{ kind: 'enable', modKey: m.key }]);
    m = session.inventory.value!.mods.find((x) => x.projectId === FERRITE)!;
    await applyDraft([{ kind: 'remove', modKey: m.key }]);
    expect(session.inventory.value!.mods).toEqual([]);
  }, 600_000);

  it('installs a required dependency with its dependent (Sodium with Sodium Extra, Fabric 1.20.1)', async () => {
    await session.selectInstance(ids.fabric!);
    const v = await session.backend.projectVersions!(ids.fabric!, 'modrinth', 'PtjYWJkn');
    const plan = await applyDraft([{ kind: 'install', provider: 'modrinth', projectId: 'PtjYWJkn', name: 'Sodium Extra', versionId: v[0]!.id }]);
    log('dependency plan', plan.items.map((i) => i.name), plan.issues.map((i) => i.message));
    expect(plan.issues.some((i) => i.code === 'dependency-included')).toBe(true);
    expect(session.inventory.value!.mods.map((x) => x.projectId)).toEqual(expect.arrayContaining(['PtjYWJkn', 'AANobbMI']));
  }, 600_000);

  let packBytes: Uint8Array;
  let packOverrides: OverrideFile[];
  it('imports a Forge 1.20.1 .mrpack with overrides (260 config files) through upload, review and apply', async () => {
    const f = await modrinthFile('DG5Fn9Sz');
    const p = newProject({
      name: 'Real import pack', version: '1.0.0', minecraftVersion: '1.20.1', loader: { kind: 'forge', version: '47.4.28' },
      mods: [{ key: modKey('modrinth', FERRITE), name: 'FerriteCore', provider: 'modrinth', projectId: FERRITE, versionId: 'DG5Fn9Sz', required: true, pinned: false, verified: true, origin: 'import',
        file: { path: `mods/${f.filename}`, size: f.size, sha1: f.hashes.sha1, sha512: f.hashes.sha512, downloads: [f.url] } }],
    });
    packOverrides = [
      ...Array.from({ length: 259 }, (_, i) => ({ root: 'overrides' as const, path: `config/awake-test/file-${String(i).padStart(3, '0')}.toml`, data: enc(`value = ${i}\n`) })),
      { root: 'client-overrides', path: 'config/awake-client.txt', data: enc('client side\n') },
    ];
    packBytes = buildExport(p, planExport(p, 'mrpack'), packOverrides);
    const preview = await importPack(bytesSource(packBytes), 'real.mrpack');
    expect(preview.project.overrides.length).toBe(260);
    const { ins, plan, id } = await importArchive(packBytes, 'mrpack', 'Real import pack');
    log('inspect', ins.minecraftVersion, ins.loader, ins.files.length, ins.projects, ins.downloadCount, ins.warnings);
    expect(ins.loader).toEqual({ kind: 'forge', version: '47.4.28' });
    expect(plan.items.filter((i) => i.action === 'override').length).toBe(260);
    expect(plan.items.filter((i) => i.action === 'install').map((i) => i.name)).toEqual([f.filename]);
    await session.apply();
    expect(session.review.phase, session.review.error?.message ?? JSON.stringify(session.review.operation)).toBe('done');
    const dir = workspaceDir(root, 'Real import pack');
    const all = files(dir);
    expect(all.filter((x) => /awake-test[\\/]file-\d+\.toml$/.test(x)).length).toBe(259);
    expect(readFileSync(all.find((x) => x.endsWith('awake-client.txt'))!, 'utf8')).toBe('client side\n');
    await session.selectInstance(id);
    expect(session.inventory.value!.mods.map((x) => x.installed?.id)).toEqual(['DG5Fn9Sz']);
    ids.imported = id;
  }, 900_000);

  it('round-trips: snapshot export of the imported workspace re-imports into a new workspace', async () => {
    const snap = await session.backend.snapshotWorkspace!(ids.imported!);
    expect(snap.skipped).toEqual([]);
    const p = newProject({ name: 'Round trip', minecraftVersion: snap.minecraftVersion, loader: snap.loader, mods: snap.mods.map((m) => ({
      key: modKey(m.provider, m.projectId), name: m.name, provider: m.provider, projectId: m.projectId, versionId: m.versionId, required: true, pinned: false, verified: true, origin: 'import' as const,
      file: { path: `mods/${m.fileName}`, size: m.size, sha1: m.sha1, sha512: m.sha512, downloads: [m.url] },
    })) });
    const exported = buildExport(p, planExport(p, 'mrpack'), packOverrides);
    const again = await importPack(bytesSource(exported), 'round.mrpack');
    expect(again.project.mods.map((m) => m.versionId)).toEqual(['DG5Fn9Sz']);
    const { plan } = await importArchive(exported, 'mrpack', 'Round trip');
    expect(plan.items.filter((i) => i.action === 'override').length).toBe(260);
    await session.apply();
    expect(session.review.phase).toBe('done');
  }, 900_000);

  it('rejects ZIP64, non-Modrinth download hosts and CurseForge-hosted files with actionable errors', async () => {
    const b = session.backend;
    const zip64 = new Uint8Array(readFileSync('tests/fixtures/packs/zip64.mrpack'));
    const tok = await b.uploadImport!(new Blob([zip64 as BlobPart]));
    await expect(b.inspectImport!(tok, 'mrpack')).rejects.toMatchObject({ code: 'invalid-archive' });
    await b.discardImport!(tok);

    const f = await modrinthFile('DG5Fn9Sz');
    const gh = newProject({ name: 'Host', minecraftVersion: '1.20.1', loader: { kind: 'forge', version: '47.4.28' }, mods: [{ key: 'file:x', name: 'x', provider: 'manual', required: true, pinned: false, verified: true, origin: 'import',
      file: { path: `mods/${f.filename}`, size: f.size, sha1: f.hashes.sha1, sha512: f.hashes.sha512, downloads: [`https://github.com/example/example/releases/download/1/${f.filename}`] } }] });
    const hostPack = buildExport(gh, planExport(gh, 'mrpack'));
    const err = await importArchive(hostPack, 'mrpack', 'Rejected host').catch((e) => e);
    log('host error', err.code, err.detail, err.message);
    expect(err.code).toBe('provider-restricted');

    // CurseForge ZIP fixture: overrides install; a CurseForge-hosted file needs authorized API access.
    const manifest = (files: unknown[]) => enc(JSON.stringify({ minecraft: { version: '1.20.1', modLoaders: [{ id: 'forge-47.4.28', primary: true }] }, manifestType: 'minecraftModpack', manifestVersion: 1, name: 'CF fixture', version: '1', author: 'test', files, overrides: 'overrides' }));
    const cfOk = writeZip([{ path: 'manifest.json', data: manifest([]) }, { path: 'overrides/config/cf-fixture.toml', data: enc('cf = true\n') }]);
    const ok = await importArchive(cfOk, 'curseforge', 'CF fixture');
    expect(ok.plan.items.map((i) => [i.action, i.name])).toEqual([['override', 'config/cf-fixture.toml']]);
    await session.apply();
    expect(session.review.phase).toBe('done');
    const cfMod = writeZip([{ path: 'manifest.json', data: manifest([{ projectID: 238222, fileID: 4712866, required: true }]) }]);
    const cfErr = await importArchive(cfMod, 'curseforge', 'CF restricted').catch((e) => e);
    log('cf error', cfErr.code, cfErr.detail, cfErr.message);
    expect(['provider-restricted', 'unsupported']).toContain(cfErr.code);
  }, 900_000);

  it('recovers an Apply interrupted by killing the helper, and keeps every workspace across the restart', async () => {
    // A 260-file plan gives the kill a window inside Apply.
    const { plan, id } = await importArchive(packBytes, 'mrpack', 'Interrupted pack');
    const acc = await session.backend.applyPlan({ planId: plan.planId, planHash: plan.planHash, baseRevision: plan.baseRevision, idempotencyKey: crypto.randomUUID() });
    let seen = '';
    for (let i = 0; i < 200; i++) {
      seen = (await session.backend.getOperation(acc.operationId)).state;
      if (['backing_up', 'applying', 'verifying', 'completed'].includes(seen)) break;
      await new Promise((r) => setTimeout(r, 20));
    }
    log('killing helper during', seen);
    t.kill();
    await new Promise((r) => setTimeout(r, 1500));
    const after = createSession(client(), { pollMs: 300 });
    await after.connect();
    let op = await after.backend.getOperation(acc.operationId);
    for (let i = 0; i < 300 && !['completed', 'rolled_back', 'failed', 'cancelled'].includes(op.state); i++) {
      if (op.state === 'recovery_required' && after.backend.runRecovery) await after.runRecovery(acc.operationId);
      await new Promise((r) => setTimeout(r, 300));
      op = await after.backend.getOperation(acc.operationId);
    }
    log('after restart:', op.state, op.error);
    expect(['completed', 'rolled_back']).toContain(op.state);
    await after.refreshInstances();
    const names = after.state.instances.map((i) => i.name);
    for (const n of ['Real vanilla 1.20.1', 'Real fabric 1.20.1', 'Real forge 1.20.1', 'Real neoforge 1.21.1', 'Real quilt 1.20.1', 'Real import pack', 'Interrupted pack']) expect(names).toContain(n);
    const w = after.state.instances.find((i) => i.id === id)!;
    expect(w.manageable).toBe(true);
    await after.selectInstance(id);
    const n = files(workspaceDir(root, 'Interrupted pack')).filter((x) => /awake-test[\\/]file-\d+\.toml$/.test(x)).length;
    log('interrupted workspace config files:', n, 'mods:', after.inventory.value!.mods.length);
    expect(n === 0 || n === 259).toBe(true); // all or nothing, never a partial pack
  }, 900_000);
});

